#!/usr/bin/env python3
"""Convert a 16 kHz mono 16-bit PCM WAV into a C header for flash storage.

Usage: tools/wav_to_header.py in.wav out.h

The header embeds the COMPLETE WAV file (RIFF header + PCM payload) as a
byte array plus its length:

    const uint8_t OFFLINE_VOICE_WAV[] PROGMEM = { ... };
    const size_t OFFLINE_VOICE_WAV_LEN = <bytes>;

Why the whole file and not stripped PCM: the firmware plays the clip
through ESP8266Audio's AudioGeneratorWAV over an AudioFileSourcePROGMEM
(the same generator + AudioOutputM5Speaker path as TTS), and that
generator parses the RIFF header itself. Regenerating the header for a
new recording is therefore just: run this script on the new WAV.

Format is enforced: anything that is not 16 kHz, mono, 16-bit, uncompressed
PCM makes the script exit non-zero with a message on stderr, and no header
is written. Stdlib only.
"""

import struct
import sys
import wave
from pathlib import Path

SAMPLE_RATE = 16000
CHANNELS = 1
SAMPLE_WIDTH_BYTES = 2


def wav_to_header(in_path: Path, out_path: Path) -> None:
    try:
        with wave.open(str(in_path), "rb") as wav:
            if wav.getcomptype() != "NONE":
                raise ValueError(
                    "unsupported compression type {!r}: expected uncompressed PCM".format(
                        wav.getcomptype()
                    )
                )
            rate = wav.getframerate()
            channels = wav.getnchannels()
            width = wav.getsampwidth()
            frames = wav.getnframes()
            pcm = wav.readframes(frames)
    except (wave.Error, EOFError, struct.error, OSError) as exc:
        raise ValueError("cannot read {} as a WAV file: {}".format(in_path, exc)) from exc
    problems = []
    if rate != SAMPLE_RATE:
        problems.append("sample rate {} Hz (expected {} Hz)".format(rate, SAMPLE_RATE))
    if channels != CHANNELS:
        problems.append("channels {} (expected {})".format(channels, CHANNELS))
    if width != SAMPLE_WIDTH_BYTES:
        problems.append("sample width {} bytes (expected {} bytes)".format(width, SAMPLE_WIDTH_BYTES))
    if problems:
        raise ValueError("invalid WAV format in {}: {}".format(in_path, "; ".join(problems)))
    if len(pcm) != frames * width:
        raise ValueError("truncated PCM data in {}".format(in_path))

    data = in_path.read_bytes()

    lines = []
    lines.append("// Generated by tools/wav_to_header.py. Do not edit by hand.")
    lines.append("// Complete WAV file (RIFF header + PCM), embedded in flash for")
    lines.append("// playback via AudioGeneratorWAV + AudioFileSourcePROGMEM.")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("#include <stddef.h>")
    lines.append("")
    lines.append("const uint8_t OFFLINE_VOICE_WAV[] PROGMEM = {")
    per_line = 12
    for offset in range(0, len(data), per_line):
        chunk = data[offset : offset + per_line]
        rendered = ", ".join("0x{:02x}".format(byte) for byte in chunk)
        comma = "," if offset + per_line < len(data) else ""
        lines.append("    {}{}".format(rendered, comma))
    lines.append("};")
    lines.append("const size_t OFFLINE_VOICE_WAV_LEN = {};".format(len(data)))
    lines.append("const uint32_t OFFLINE_VOICE_SAMPLE_RATE = {};".format(SAMPLE_RATE))
    lines.append("const uint16_t OFFLINE_VOICE_CHANNELS = {};".format(CHANNELS))
    lines.append("const uint16_t OFFLINE_VOICE_BITS_PER_SAMPLE = {};".format(SAMPLE_WIDTH_BYTES * 8))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv) -> int:
    if len(argv) != 3:
        print("usage: wav_to_header.py in.wav out.h", file=sys.stderr)
        return 2
    in_path, out_path = Path(argv[1]), Path(argv[2])
    try:
        wav_to_header(in_path, out_path)
    except ValueError as exc:
        print("wav_to_header: error: {}".format(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
